// Source locations and provenance shared by propositions and relation facts.
use tower_lsp::lsp_types::Range;

use crate::acorn_value::AcornValue;
use crate::module::ModuleId;

// The different reasons that can lead us to create a proposition.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SourceType {
    // An axiom, which may have a name.
    Axiom(Option<String>),

    // A theorem which may have a name.
    Theorem(Option<String>),

    // An anonymous proposition that has previously been proved
    Anonymous,

    // A type definition and the member or principle that contributes this fact.
    TypeDefinition(String, String),

    // The relationship between a concrete type and its declared class.
    Instance(String, String),

    // The value specializes during monomorphization; its declared source name does not.
    ConstantDefinition(AcornValue, String),

    // A premise for a block that contains the current environment
    Premise,

    // A proposition generated by negating a goal, for the sake of proving it by contradiction
    NegatedGoal,
}

// The information about where a proposition comes from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Source {
    // The module where this value was defined
    pub module: ModuleId,

    // The range in the source document that corresponds to the value's definition
    pub range: Range,

    // How the expression at this location was turned into a proposition
    pub source_type: SourceType,

    // Whether this source may be exported or retained as reusable premise advice.
    // Node admission also intersects this with its actual top-level environment.
    pub importable: bool,

    // Lexical declaration depth. Contextual proof roles are independent metadata.
    pub depth: u32,
}

impl Source {
    pub fn mock() -> Source {
        Source {
            module: 0,
            range: Range::default(),
            source_type: SourceType::Anonymous,
            importable: true,
            depth: 0,
        }
    }

    // The line the user sees, starting from 1.
    pub fn user_visible_line(&self) -> u32 {
        self.range.start.line + 1
    }

    pub fn description(&self) -> String {
        match &self.source_type {
            SourceType::Axiom(name) => match name {
                Some(name) => format!("the '{}' axiom", name),
                None => "an anonymous axiom".to_string(),
            },
            SourceType::Theorem(name) => match name {
                Some(name) => format!("the '{}' theorem", name),
                None => "an anonymous theorem".to_string(),
            },
            SourceType::Anonymous => format!("line {}", self.user_visible_line()),
            SourceType::TypeDefinition(name, _) => format!("the '{}' definition", name),
            SourceType::Instance(name, class) => {
                format!("the '{}: {}' relationship", name, class)
            }
            SourceType::ConstantDefinition(value, _) => format!("the '{}' definition", value),
            SourceType::Premise => "an assumed premise".to_string(),
            SourceType::NegatedGoal => "negating the goal".to_string(),
        }
    }

    // A module-local identifier for selecting a source across common edits.
    // Multiple facts can share a source; this is not a unique proof-step identifier.
    // Anonymous claims fall back to their one-based source line.
    pub fn name(&self) -> Option<String> {
        self.fact_name()
    }

    pub fn fact_name(&self) -> Option<String> {
        match &self.source_type {
            SourceType::Axiom(name) | SourceType::Theorem(name) => Some(
                name.clone()
                    .unwrap_or_else(|| self.user_visible_line().to_string()),
            ),
            SourceType::Anonymous => Some(self.user_visible_line().to_string()),
            SourceType::TypeDefinition(type_name, member) => Some(format!("{type_name}.{member}")),
            SourceType::Instance(name, class) => Some(format!("{name}.instance.{class}")),
            SourceType::ConstantDefinition(_, name) => Some(name.clone()),
            SourceType::Premise | SourceType::NegatedGoal => None,
        }
    }

    // Identity within this loaded project. Convert the module ID to its canonical
    // ModuleRef before retaining this identity across project reloads.
    pub fn qualified_name(&self) -> Option<(ModuleId, String)> {
        self.qualified_fact_name()
    }

    pub fn qualified_fact_name(&self) -> Option<(ModuleId, String)> {
        self.fact_name().map(|name| (self.module, name))
    }

    pub fn is_axiom(&self) -> bool {
        match self.source_type {
            SourceType::Axiom(_) => true,
            _ => false,
        }
    }
}
