// Modified for Venticorn: theorem and axiom names are optional source metadata.
use std::fmt;

use tower_lsp::lsp_types::Range;

use crate::acorn_type::AcornType;
use crate::acorn_value::AcornValue;
use crate::module::ModuleId;
use crate::proof_step::Truthiness;

// The different reasons that can lead us to create a proposition.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SourceType {
    // An axiom, which may have a name.
    Axiom(Option<String>),

    // A theorem which may have a name.
    Theorem(Option<String>),

    // An anonymous proposition that has previously been proved
    Anonymous,

    // A type definition and the member or principle that contributes this fact.
    TypeDefinition(String, String),

    // The relationship between a concrete type and its declared class.
    Instance(String, String),

    // The value specializes during monomorphization; its declared source name does not.
    ConstantDefinition(AcornValue, String),

    // A premise for a block that contains the current environment
    Premise,

    // A proposition generated by negating a goal, for the sake of proving it by contradiction
    NegatedGoal,
}

// The information about where a proposition comes from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Source {
    // The module where this value was defined
    pub module: ModuleId,

    // The range in the source document that corresponds to the value's definition
    pub range: Range,

    // How the expression at this location was turned into a proposition
    pub source_type: SourceType,

    // Whether this source may be exported or retained as reusable premise advice.
    // Node admission also intersects this with its actual top-level environment.
    pub importable: bool,

    // Lexical declaration depth. Contextual proof roles are independent metadata.
    pub depth: u32,
}

impl Source {
    pub fn mock() -> Source {
        Source {
            module: 0,
            range: Range::default(),
            source_type: SourceType::Anonymous,
            importable: true,
            depth: 0,
        }
    }

    // The line the user sees, starting from 1.
    pub fn user_visible_line(&self) -> u32 {
        self.range.start.line + 1
    }

    pub fn description(&self) -> String {
        match &self.source_type {
            SourceType::Axiom(name) => match name {
                Some(name) => format!("the '{}' axiom", name),
                None => "an anonymous axiom".to_string(),
            },
            SourceType::Theorem(name) => match name {
                Some(name) => format!("the '{}' theorem", name),
                None => "an anonymous theorem".to_string(),
            },
            SourceType::Anonymous => format!("line {}", self.user_visible_line()),
            SourceType::TypeDefinition(name, _) => format!("the '{}' definition", name),
            SourceType::Instance(name, class) => {
                format!("the '{}: {}' relationship", name, class)
            }
            SourceType::ConstantDefinition(value, _) => format!("the '{}' definition", value),
            SourceType::Premise => "an assumed premise".to_string(),
            SourceType::NegatedGoal => "negating the goal".to_string(),
        }
    }

    // A module-local identifier for selecting a source across common edits.
    // Multiple facts can share a source; this is not a unique proof-step identifier.
    // Anonymous claims fall back to their one-based source line.
    pub fn name(&self) -> Option<String> {
        self.fact_name()
    }

    pub fn fact_name(&self) -> Option<String> {
        match &self.source_type {
            SourceType::Axiom(name) | SourceType::Theorem(name) => Some(
                name.clone()
                    .unwrap_or_else(|| self.user_visible_line().to_string()),
            ),
            SourceType::Anonymous => Some(self.user_visible_line().to_string()),
            SourceType::TypeDefinition(type_name, member) => Some(format!("{type_name}.{member}")),
            SourceType::Instance(name, class) => Some(format!("{name}.instance.{class}")),
            SourceType::ConstantDefinition(_, name) => Some(name.clone()),
            SourceType::Premise | SourceType::NegatedGoal => None,
        }
    }

    // Identity within this loaded project. Convert the module ID to its canonical
    // ModuleRef before retaining this identity across project reloads.
    pub fn qualified_name(&self) -> Option<(ModuleId, String)> {
        self.qualified_fact_name()
    }

    pub fn qualified_fact_name(&self) -> Option<(ModuleId, String)> {
        self.fact_name().map(|name| (self.module, name))
    }

    pub fn is_axiom(&self) -> bool {
        match self.source_type {
            SourceType::Axiom(_) => true,
            _ => false,
        }
    }
}

// A value along with information on where to find it in the source.
#[derive(Debug, Clone)]
pub struct Proposition {
    // A boolean value. The essence of the proposition is "value is true".
    pub value: AcornValue,

    // Where this proposition came from.
    pub source: Source,

    // An explicit proof-context role never changes the declaration source.
    contextual_truthiness: Option<Truthiness>,
}

impl fmt::Display for Proposition {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.value.fmt(f)
    }
}

impl Proposition {
    // Construct a proposition with its source's default lexical role.
    pub fn new(value: AcornValue, source: Source) -> Self {
        Self {
            value,
            source,
            contextual_truthiness: None,
        }
    }

    // Supply a role for this proof context without rewriting source provenance.
    pub fn with_truthiness(mut self, truthiness: Truthiness) -> Self {
        self.contextual_truthiness = Some(truthiness);
        self
    }

    // Effective role in this proof context, falling back to the declaration scope.
    pub fn truthiness(&self) -> Truthiness {
        self.contextual_truthiness.unwrap_or_else(|| {
            if matches!(self.source.source_type, SourceType::NegatedGoal) {
                Truthiness::Counterfactual
            } else if self.source.depth == 0 {
                Truthiness::Factual
            } else {
                Truthiness::Hypothetical
            }
        })
    }

    // Set the declaration location without changing exportability or source identity.
    pub fn with_depth(mut self, depth: u32) -> Self {
        self.source.depth = depth;
        self
    }

    pub fn theorem(
        axiomatic: bool,
        value: AcornValue,
        module: ModuleId,
        range: Range,
        name: Option<String>,
    ) -> Proposition {
        let source_type = if axiomatic {
            SourceType::Axiom(name)
        } else {
            SourceType::Theorem(name)
        };
        Proposition::new(
            value,
            Source {
                module,
                range,
                source_type,
                importable: true,
                depth: 0,
            },
        )
    }

    pub fn anonymous(value: AcornValue, module: ModuleId, range: Range) -> Proposition {
        Proposition::new(
            value,
            Source {
                module,
                range,
                source_type: SourceType::Anonymous,
                importable: false,
                depth: 0,
            },
        )
    }

    // The relationship marker is separate from the block that proves its laws.
    pub fn instance(
        value: Option<AcornValue>,
        module: ModuleId,
        range: Range,
        name: String,
        class: String,
    ) -> Proposition {
        Proposition::new(
            value.unwrap_or(AcornValue::Bool(true)),
            Source {
                module,
                range,
                source_type: SourceType::Instance(name, class),
                importable: true,
                depth: 0,
            },
        )
    }

    // The constraint block proves inhabitation; its exported claim remains vacuous.
    pub fn inhabited(module: ModuleId, type_name: &str, range: Range) -> Proposition {
        Self::type_member_definition(
            AcornValue::Bool(true),
            module,
            range,
            type_name.to_string(),
            "constraint".into(),
        )
    }

    // Compatibility constructor for callers without a more specific member name.
    pub fn type_definition(
        value: AcornValue,
        module: ModuleId,
        range: Range,
        name: String,
    ) -> Proposition {
        Self::type_member_definition(value, module, range, name, "definition".into())
    }

    pub fn type_member_definition(
        value: AcornValue,
        module: ModuleId,
        range: Range,
        name: String,
        member: String,
    ) -> Proposition {
        Proposition::new(
            value,
            Source {
                module,
                range,
                source_type: SourceType::TypeDefinition(name, member),
                importable: true,
                depth: 0,
            },
        )
    }

    pub fn constant_definition(
        value: AcornValue,
        module: ModuleId,
        range: Range,
        constant: AcornValue,
    ) -> Proposition {
        let name = constant
            .as_name()
            .map(|(_, name)| name.to_string())
            .unwrap_or_else(|| constant.to_string());
        Self::named_constant_definition(value, module, range, constant, name)
    }

    pub fn named_constant_definition(
        value: AcornValue,
        module: ModuleId,
        range: Range,
        constant: AcornValue,
        name: String,
    ) -> Proposition {
        Proposition::new(
            value,
            Source {
                module,
                range,
                source_type: SourceType::ConstantDefinition(constant, name),
                importable: true,
                depth: 0,
            },
        )
    }

    pub fn premise(value: AcornValue, module: ModuleId, range: Range) -> Proposition {
        Proposition::new(
            value,
            Source {
                module,
                range,
                source_type: SourceType::Premise,
                importable: false,
                depth: 0,
            },
        )
    }

    pub fn with_negated_goal(&self, value: AcornValue) -> Proposition {
        Proposition::new(
            value,
            Source {
                module: self.source.module,
                range: self.source.range,
                source_type: SourceType::NegatedGoal,
                importable: false,
                depth: self.source.depth,
            },
        )
        .with_truthiness(Truthiness::Counterfactual)
    }

    // Just changes the value while keeping the other stuff intact
    pub fn with_value(&self, value: AcornValue) -> Proposition {
        Self {
            value,
            source: self.source.clone(),
            contextual_truthiness: self.contextual_truthiness,
        }
    }

    // Theorems and axioms can have names
    // Compatibility name for theorem/axiom declarations, distinct from Source::name.
    pub fn name(&self) -> Option<&str> {
        self.theorem_name()
    }

    pub fn theorem_name(&self) -> Option<&str> {
        match &self.source.source_type {
            SourceType::Axiom(name) | SourceType::Theorem(name) => name.as_deref(),
            _ => None,
        }
    }

    // Substitute provided type variables while preserving unresolved formals.
    pub fn instantiate(&self, params: &[(String, AcornType)]) -> Proposition {
        let value = self.value.instantiate(params);
        let source = match &self.source.source_type {
            SourceType::ConstantDefinition(v, name) => Source {
                source_type: SourceType::ConstantDefinition(v.instantiate(params), name.clone()),
                ..self.source.clone()
            },
            _ => self.source.clone(),
        };
        Self {
            value,
            source,
            contextual_truthiness: self.contextual_truthiness,
        }
    }
}
